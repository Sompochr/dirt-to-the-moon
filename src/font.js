const CELL = 8; // atlas cell size
const SPACE = 3;
const parsed = {};
const order = Object.keys(GLYPHS);
order.forEach((ch, i) => {
  const rows = GLYPHS[ch].split('|');
  parsed[ch] = { rows, w: rows[0].length, i };
});

const atlases = new Map();
function atlasFor(color) {
  let a = atlases.get(color);
  if (a) return a;
  a = document.createElement('canvas');
  a.width = CELL * order.length;
  a.height = CELL;
  const g = a.getContext('2d');
  g.fillStyle = color;
  for (const ch of order) {
    const { rows, i } = parsed[ch];
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') g.fillRect(i * CELL + x, y, 1, 1);
    });
  }
  atlases.set(color, a);
  return a;
}

function glyphWidth(ch) {
  if (ch === ' ') return SPACE;
  const g = parsed[ch];
  return g ? g.w : SPACE;
}

export function textWidth(text, scale = 1) {
  const s = String(text).toUpperCase();
  let w = 0;
  for (let i = 0; i < s.length; i++) w += glyphWidth(s[i]) + (i < s.length - 1 ? 1 : 0);
  return w * scale;
}

// align: 'left' | 'center' | 'right'. y is the top of the text. Height = 7 * scale.
export function drawText(ctx, text, x, y, opts = {}) {
  const { scale = 1, color = '#f4f4f4', align = 'left', shadow = '#1a1c2c' } = opts;
  const s = String(text).toUpperCase();
  let cx = Math.round(align === 'center' ? x - textWidth(s, scale) / 2 : align === 'right' ? x - textWidth(s, scale) : x);
  const cy = Math.round(y);
  const passes = shadow ? [[shadow, scale], [color, 0]] : [[color, 0]];
  const startX = cx;
  for (const [col, off] of passes) {
    const atlas = atlasFor(col);
    cx = startX;
    for (let i = 0; i < s.length; i++) {
      const ch = s[i];
      const g = parsed[ch];
      if (g) ctx.drawImage(atlas, g.i * CELL, 0, g.w, 7, cx + off, cy + off, g.w * scale, 7 * scale);
      cx += (glyphWidth(ch) + 1) * scale;
    }
  }
}
